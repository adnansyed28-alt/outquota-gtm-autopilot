import csv
import os
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, "sample-data")
OUT = os.path.join(ROOT, "docs", "run_summary.md")


def read(name):
    with open(os.path.join(DATA, name), newline="") as f:
        return list(csv.DictReader(f))


def main():
    raw = read("leads_batch.csv")
    rejected = read("leads_rejected.csv")
    scored = read("leads_scored.csv")

    reasons = Counter(r["reject_reason"] for r in rejected)
    mix = Counter(f"{r['tier']} / {r['intent_level']}" for r in scored)

    lines = [
        "# Pipeline run summary", "",
        "_Generated by `pipeline/report.py` from synthetic data._", "",
        "## Funnel", "",
        "| Stage | Leads |", "|---|---|",
        f"| Raw leads | {len(raw)} |",
        f"| Rejected | {len(rejected)} |",
        f"| Qualified and scored | {len(scored)} |", "",
        "## Why leads were rejected", "",
        "| Reason | Count |", "|---|---|",
    ]
    for reason, count in reasons.most_common():
        lines.append(f"| {reason} | {count} |")

    lines += ["", "## Tier and intent mix", "", "| Segment | Leads |", "|---|---|"]
    for seg, count in sorted(mix.items()):
        lines.append(f"| {seg} | {count} |")

    lines += ["", "## Top 10 leads to contact first", "",
              "| # | Segment | Score | Contact | Company | Why |",
              "|---|---|---|---|---|---|"]
    for i, r in enumerate(scored[:10], 1):
        lines.append(
            f"| {i} | {r['tier']} / {r['intent_level']} | {r['total_score']} | "
            f"{r['contact_name']}, {r['title']} | {r['company_name']} | {r['why']} |"
        )

    researched = [r for r in scored if r.get("research_hook")]
    lines += ["", "## Researched leads (LLM, evidence-backed)", "",
              "| Segment | Contact | Company | Evidence | Suggested opener |",
              "|---|---|---|---|---|"]
    for r in researched:
        lines.append(
            f"| {r['tier']} / {r['intent_level']} | {r['contact_name']}, {r['title']} | "
            f"{r['company_name']} | {r['research_quote']} | {r['research_hook']} |"
        )

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
